function renderBodySection({ title, meta, copyKind, copyIndex, body, className = '', actionHtml = '' }) {
  const actions = actionHtml || renderCopyButton(copyKind, {
    index: copyIndex,
    className: copyKind === 'chapterBody' ? 'kakuyomu-chapter-copy' : '',
  });
  return `
    <section class="kakuyomu-body-block${className ? ` ${className}` : ''}">
      <div class="kakuyomu-body-block-head">
        <div>
          <div class="kakuyomu-body-block-title">${Ce(title)}</div>
          <div class="kakuyomu-body-block-meta">${Ce(meta)}</div>
        </div>
        <div class="kakuyomu-body-block-actions">${actions}</div>
      </div>
      <pre class="kakuyomu-body-preview${copyKind === 'chapterBody' ? ' kakuyomu-chapter-preview' : ''}">${Ce(body)}</pre>
    </section>
  `;
}

function renderBodySections(preview) {
  const fullBody = renderBodySection({
    title: '全文表示',
    meta: `${charLength(preview.body)}字`,
    copyKind: 'body',
    body: preview.body,
  });
  const chapters = preview.chapters?.length
    ? `
      <div class="kakuyomu-chapter-visible-list" aria-label="章ごとの本文表示">
        ${preview.chapters.map((chapter, index) => renderBodySection({
          title: chapter.label,
          meta: `${charLength(chapter.body)}字`,
          copyKind: 'chapterBody',
          copyIndex: index,
          body: chapter.body,
          className: 'kakuyomu-chapter-block',
          actionHtml: [
            renderCopyButton('chapterTitle', {
              label: '章タイトルコピー',
              title: `${chapter.label}をコピー`,
              index,
              className: 'kakuyomu-chapter-title-copy',
            }),
            renderCopyButton('chapterBody', {
              label: '本文コピー',
              title: `${chapter.label}の本文だけをコピー`,
              index,
              className: 'kakuyomu-chapter-copy',
            }),
          ].join(''),
        })).join('')}
      </div>
    `
    : '';
  return `<div class="kakuyomu-body-sections">${fullBody}${chapters}</div>`;
}

