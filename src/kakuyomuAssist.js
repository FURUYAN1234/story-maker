export function buildKakuyomuPreview({ storyText = '', settings = {} } = {}) {
  const body = stripStoryMakerFooter(storyText);
  const title = extractStoryTitle(body, settings);
  const submissionBody = dropTitleLine(body, title);
  const genre = suggestKakuyomuGenre(settings);
  const selfRatings = detectSelfRatings(body);
  const tags = createKakuyomuTags({ settings, kakuyomuGenre: genre });
  const chapters = splitKakuyomuBodyChapters(submissionBody);
  const preview = {
    title,
    workStatus: inferWorkStatus(settings),
    workType: 'オリジナル小説',
    genre,
    catchCopy: buildCatchCopy(body, title, settings),
    introduction: buildIntroduction(body, title, settings),
    selfRatings,
    tags,
    aiUseTag: AI_USE_TAG,
    contest: '応募しない（応募する場合は対象コンテストを選択）',
    userEvent: '参加しない（必要な自主企画だけ選択）',
    collection: '未設定',
    imageColor: chooseImageColor(genre),
    adDisplay: '広告を表示する',
    reservedPublish: '表示する',
    updateSchedule: '設定しない',
    body: submissionBody,
    chapters,
  };
  preview.copyAll = formatKakuyomuPreview(preview);
  return preview;
}

export function splitKakuyomuBodyChapters(body = '') {
  const text = stripStoryMakerFooter(body);
  const lines = normalizeText(text).split('\n');
  const headingPattern = CHAPTER_HEADING_PATTERN;
  const chapters = [];
  const preface = [];
  let current = null;

  for (const line of lines) {
    if (headingPattern.test(line.trim())) {
      if (current) chapters.push(current);
      const label = compactSpaces(line.replace(/^[#\s\u3000【]+|[】\s\u3000]+$/gu, ''));
      current = {
        label: limitJapaneseChars(label || `第${chapters.length + 1}章`, 32),
        lines: [],
      };
      preface.length = 0;
    } else if (current) {
      current.lines.push(line);
    } else if (line.trim()) {
      preface.push(line);
    }
  }
  if (current) chapters.push(current);
  return chapters
    .map((chapter, index) => ({
      label: chapter.label || `第${index + 1}章`,
      body: chapter.lines.join('\n').trim(),
    }))
    .filter(chapter => charLength(chapter.body) >= 40);
}

function readActiveChipText(selector) {
  return document.querySelector(selector)?.textContent?.trim() || '';
}

function readInputValue(id) {
  return document.getElementById(id)?.value?.trim() || '';
}

function readAxisValue(axis) {
  return (
    readInputValue(`${axis}-custom`)
    || readActiveChipText(`#${axis}-sub-chips .chip.active`)
    || readActiveChipText(`#${axis}-cat-chips .chip.active`)
  );
}

function readSettingsFromDom() {
  return {
    modeLabel: readInputValue('mode-custom') || readActiveChipText('#mode-chips .chip.active'),
    theme: readAxisValue('theme'),
    genre: readAxisValue('genre'),
    worldview: readAxisValue('worldview'),
    target: readAxisValue('target'),
    era: readAxisValue('era'),
    ending: readAxisValue('ending'),
    narration: readAxisValue('narr'),
  };
}

