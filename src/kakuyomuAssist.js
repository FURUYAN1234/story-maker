function normalizeText(value) {
  return String(value || '').replace(/\r\n?/g, '\n').trim();
}

function compactSpaces(value) {
  return String(value || '').replace(/\s+/g, ' ').trim();
}

function charLength(value) {
  return Array.from(String(value || '')).length;
}

export function limitJapaneseChars(value, max, suffix = '') {
  const chars = Array.from(String(value || '').trim());
  if (chars.length <= max) return chars.join('');
  const suffixChars = Array.from(suffix);
  const keep = Math.max(0, max - suffixChars.length);
  return `${chars.slice(0, keep).join('')}${suffix}`;
}

export function stripStoryMakerFooter(text) {
  let current = normalizeText(text);
  for (let i = 0; i < 3; i += 1) {
    current = current.replace(STORY_FOOTER_PATTERN, '').trim();
  }
  return current;
}

function cleanTitleCandidate(value) {
  return compactSpaces(value)
    .replace(/^[#＃\s]+/, '')
    .replace(/^["'「『【]+|["'」』】]+$/g, '')
    .replace(/[。！？!?]+$/g, '')
    .trim();
}

function isLikelyTitleLine(value) {
  const title = cleanTitleCandidate(value);
  return (
    title.length > 0
    && charLength(title) <= 42
    && !/[。！？!?]$/.test(value)
    && !/^(第[0-9０-９一二三四五六七八九十]+[章節話]|Created By|Generated By)/i.test(title)
  );
}

export function extractStoryTitle(text, settings = {}) {
  const body = stripStoryMakerFooter(text);
  const labeled = body.match(/(?:^|\n)\s*(?:タイトル|題名|作品名)\s*[:：]\s*([^\n]{1,80})/);
  if (labeled) return limitJapaneseChars(cleanTitleCandidate(labeled[1]), 42);

  const lines = body.split('\n').map(line => line.trim()).filter(Boolean);
  const bracketed = lines[0]?.match(/^【(.{1,60})】$/);
  if (bracketed) return limitJapaneseChars(cleanTitleCandidate(bracketed[1]), 42);
  const heading = lines[0]?.match(/^[#＃]+\s*(.{1,60})$/);
  if (heading) return limitJapaneseChars(cleanTitleCandidate(heading[1]), 42);
  if (lines[0] && isLikelyTitleLine(lines[0])) {
    return limitJapaneseChars(cleanTitleCandidate(lines[0]), 42);
  }

  const theme = cleanTitleCandidate(settings.theme);
  const genre = cleanTitleCandidate(settings.genre);
  if (theme) return limitJapaneseChars(`${theme}の物語`, 42);
  if (genre) return limitJapaneseChars(`${genre}の物語`, 42);
  return '名称未設定の小説';
}

function dropTitleLine(body, title) {
  const lines = normalizeText(body).split('\n');
  const normalizedTitle = cleanTitleCandidate(title);
  if (!normalizedTitle || !lines.length) return body;
  const first = cleanTitleCandidate(lines[0]);
  if (
    first === normalizedTitle
    || cleanTitleCandidate(first.replace(/^(?:タイトル|題名|作品名)\s*[:：]\s*/, '')) === normalizedTitle
  ) {
    return lines.slice(1).join('\n').trim();
  }
  return body;
}

function splitSentences(text) {
  const compact = compactSpaces(text);
  const matches = compact.match(/[^。！？!?]+[。！？!?]?/g) || [];
  return matches
    .map(sentence => sentence.trim())
    .filter(sentence => charLength(sentence) >= 8);
}

function isChapterHeadingLine(value) {
  return CHAPTER_HEADING_PATTERN.test(String(value || '').trim());
}

function stripChapterHeadingPrefix(value) {
  const line = compactSpaces(value);
  if (!line || isChapterHeadingLine(line)) return '';
  return line.replace(CHAPTER_HEADING_PREFIX_PATTERN, '').trim();
}

function storyTextForFormSummary(body, title) {
  const withoutTitle = dropTitleLine(body, title);
  return normalizeText(withoutTitle)
    .split('\n')
    .map(line => stripChapterHeadingPrefix(line))
    .filter(Boolean)
    .join('\n')
    .replace(/\n{3,}/g, '\n\n')
    .trim();
}

function contentLines(text) {
  return normalizeText(text)
    .split('\n')
    .map(line => stripChapterHeadingPrefix(line))
    .filter(line => charLength(line) >= 8)
    .filter(line => !/^(?:タイトル|題名|作品名)\s*[:：]/.test(line))
    .filter(line => !/^Created By AI Story Maker/i.test(line));
}

function buildCatchCopy(body, title, settings = {}) {
  const summaryBody = storyTextForFormSummary(body, title);
  const lead = splitSentences(summaryBody)[0] || contentLines(summaryBody)[0] || '';
  if (lead) {
    return limitJapaneseChars(lead.replace(/[。！？!?]+$/g, ''), MAX_CATCH_COPY_CHARS, '…');
  }
  const theme = compactSpaces(settings.theme || title);
  const ending = compactSpaces(settings.ending || settings.genre || '物語');
  return limitJapaneseChars(`${theme}が揺らす、${ending}の一作`, MAX_CATCH_COPY_CHARS, '…');
}

function buildIntroduction(body, title, settings = {}) {
  const summaryBody = storyTextForFormSummary(body, title);
  const sentences = splitSentences(summaryBody);
  const lines = contentLines(summaryBody);
  const lead = sentences[0] || lines[0] || '';
  const theme = compactSpaces(settings.theme || '');
  const genre = compactSpaces(settings.genre || settings.modeLabel || '物語');
  const worldview = compactSpaces(settings.worldview || '');
  const ending = compactSpaces(settings.ending || '');
  const titleLead = title && title !== '名称未設定の小説' ? `『${title}』は、` : '';
  const axes = [
    worldview ? `${worldview}を舞台に` : '',
    theme ? `${theme}を軸に` : '',
  ].filter(Boolean).join('、');
  const frame = `${titleLead}${axes ? `${axes}、` : ''}${genre}として読める一作です。`;
  const leadLine = lead
    ? `物語は「${limitJapaneseChars(lead.replace(/[。！？!?]+$/g, ''), 120, '…')}」から動き出します。`
    : '';
  const endingLine = ending ? `${ending}へ向かって、` : '';
  return limitJapaneseChars(
    `${frame}${leadLine}${endingLine}登場人物の迷い、選択、関係の変化を本文の温度感そのままに描きます。`,
    700,
    '…',
  );
}

export function suggestKakuyomuGenre(settings = {}) {
  const source = [
    settings.genre,
    settings.theme,
    settings.worldview,
    settings.modeLabel,
    settings.target,
  ].filter(Boolean).join(' ').toLowerCase();
  const rule = GENRE_RULES.find(item => item.pattern.test(source));
  return rule?.genre || '詩・童話・その他';
}

export function detectSelfRatings(text) {
  const body = stripStoryMakerFooter(text);
  const ratings = [];
  if (/血|惨殺|拷問|遺体|死体|虐殺|切断|内臓|グロ|残酷/.test(body)) {
    ratings.push('残酷描写有り');
  }
  if (/暴力|殴|蹴|銃|刀|刺|戦闘|殺す|殺し|爆発|戦争|武器/.test(body)) {
    ratings.push('暴力描写有り');
  }
  if (/性描写|性交|官能|性的|裸|裸体|濡れ場|成人向け/.test(body)) {
    ratings.push('性描写有り');
  }
  return [...new Set(ratings)];
}

function normalizeTag(value) {
  return limitJapaneseChars(
    compactSpaces(value)
      .replace(/^#+/, '')
      .replace(/[、。！？!?：:;；（）()\[\]{}「」『』【】]/g, '')
      .trim(),
    MAX_TAG_CHARS,
  );
}

function addTag(tags, value) {
  const tag = normalizeTag(value);
  if (!tag) return;
  if (!tags.includes(tag)) tags.push(tag);
}

export function createKakuyomuTags({ settings = {}, kakuyomuGenre = '' } = {}) {
  const tags = [];
  addTag(tags, AI_USE_TAG);
  addTag(tags, kakuyomuGenre);
  addTag(tags, String(settings.modeLabel || '').replace(/モード|風/g, ''));
  addTag(tags, settings.theme);
  addTag(tags, settings.genre);
  addTag(tags, settings.worldview);
  addTag(tags, settings.ending);
  addTag(tags, settings.target);
  addTag(tags, settings.narration);
  return tags.slice(0, MAX_TAGS);
}

function chooseImageColor(kakuyomuGenre) {
  return IMAGE_COLORS[kakuyomuGenre] || IMAGE_COLORS['詩・童話・その他'];
}

function inferWorkStatus(settings = {}) {
  const mode = String(settings.modeLabel || '');
  if (/長編|連載/.test(mode)) return '連載中';
  return '完結済（この本文だけで投稿する場合）';
}

