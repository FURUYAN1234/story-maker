// Shared by drafting, quality instructions and editorial revision. No new API stage.
const BRIEF = new Set(['4koma', '4koma_scenario', 'short_short']);
const REFLECTIVE = new Set(['essay', 'poem', 'letter', 'diary']);

export function buildStoryStructureGuidance({ mode = '', phase = 'generate' } = {}) {
  const form = REFLECTIVE.has(mode)
    ? '詩・エッセイ・手紙・日記では事件の因果や三幕を必須にしない。像・音・観察・問い・語りかけのつながりを選択形式に合わせ、主人公の選択や成長へ無理に置き換えない。'
    : mode === 'documentary'
      ? '記録作品では資料の問い・観察・証言・確認できる帰結をつなぐ。未確認の動機・証言・出来事・解決を創作しない。事実と推測を区別し、未解決は未解決のまま残す。'
      : BRIEF.has(mode)
        ? '短い尺では導入・きっかけ・応答・帰結を同じ場面へ統合してよい。コマ数・ラベル・台詞・無言の指定を保ち、脇筋や説明コマを型のために増やさない。'
        : '複数場面では人物の目的や思い込みを置き、きっかけから行動と応答を重ねる。中間では認識・関係・手段の変化を必要に応じて使い、終盤の選択や帰結へ既出の材料をつなぐ。節数・字数・出力形式は既存契約を守る。';
  const purpose = phase === 'review'
    ? '検査では型の項目不足だけで減点しない。読者が行動・情報・帰結のつながりを理解できない箇所だけを、短い引用と具体的な影響で示す。静けさ、意図した反復、不変、余白を欠陥扱いしない。'
    : phase === 'repair'
      ? '改稿では既存の事実・人物・結末・語り口を維持し、指摘されたつながりだけを既存材料で直す。危機や反転を新設して点数を稼がない。'
      : '執筆前に、その作品で読者が追う問い・期待・関係を定め、出来事または観察が次の場面へどう響くかを設計する。計画表や構造名は完成稿に出さない。';
  return [
    '【尺と形式に合わせる物語設計】',
    '三幕構成は展開を選ぶ参考とし、全項目や固定比率、15ビート、必ず中央に置く転換点を要求しない。危機・敵・死・成長・不可逆な選択・代償・どんでん返しは必須ではない。',
    '以下は共通の劇的展開の提案より優先する。ユーザーの指定した題材・結末・形式を守り、静かな余韻、悲劇、開かれた問い、不変の日常も成立した結末として扱う。シュールには合理的な説明や教訓を強制しない。',
    form,
    '冒頭と終わりの像や小物は必要なら響かせる。変化したものだけでなく、変わらなかったものの意味も描ける。場面を増やす場合は新しい応答・観察・結果を持たせ、同じ説明の水増しを避ける。',
    purpose,
  ].join('\n');
}
