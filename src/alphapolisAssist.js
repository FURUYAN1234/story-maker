export function getAlphapolisCopyValue(preview, kind, options = {}) {
  const index = Number(options.episodeIndex ?? options.tagIndex);
  if (kind === 'tag') return Number.isInteger(index) ? preview.tags?.[index] || '' : '';
  if (kind === 'chapterSetting') return Number.isInteger(index) ? preview.episodes?.[index]?.chapterSetting || '' : '';
  if (kind === 'chapterName') return Number.isInteger(index) ? preview.episodes?.[index]?.chapterName || '' : '';
  if (kind === 'sectionName') return Number.isInteger(index) ? preview.episodes?.[index]?.sectionName || '' : '';
  if (kind === 'episodeTitle') return Number.isInteger(index) ? preview.episodes?.[index]?.episodeTitle || '' : '';
  if (kind === 'episodeBody') return Number.isInteger(index) ? preview.episodes?.[index]?.body || '' : '';
  const values = {
    all: preview.copyAll,
    title: preview.title,
    introduction: preview.introduction,
    hotGenre: preview.hotGenre,
    category: preview.category,
    lengthKind: preview.lengthKind,
    writingStatus: preview.writingStatus,
    rating: preview.rating,
    tags: preview.tags.join('\n'),
    coverImage: preview.coverImage,
    impressions: preview.impressions,
    guideline: preview.guideline,
    guidelineChecks: preview.guidelineChecks.join('\n'),
    body: preview.body,
  };
  return values[kind] || '';
}

function restoreButtonText(button, originalText) {
  setTimeout(() => {
    button.textContent = originalText;
    button.classList.remove('is-copied');
  }, 1200);
}

async function copyText(value, button) {
  const text = String(value || '');
  if (!text) return;
  const originalText = button.textContent;
  try {
    await navigator.clipboard.writeText(text);
  } catch {
    const textarea = document.createElement('textarea');
    textarea.value = text;
    textarea.setAttribute('readonly', '');
    textarea.style.position = 'fixed';
    textarea.style.left = '-9999px';
    document.body.appendChild(textarea);
    textarea.select();
    document.execCommand('copy');
    textarea.remove();
  }
  button.textContent = 'コピー済み';
  button.classList.add('is-copied');
  restoreButtonText(button, originalText);
}

function saveTextFile(value, button) {
  const text = String(value || '');
  if (!text) return;
  const originalText = button.textContent;
  const blob = new Blob([text], { type: 'text/plain;charset=utf-8' });
  const url = URL.createObjectURL(blob);
  const anchor = document.createElement('a');
  anchor.href = url;
  anchor.download = buildStoryExportFileName('AlphapolisForm', 'txt');
  anchor.style.display = 'none';
  document.body.appendChild(anchor);
  anchor.click();
  anchor.remove();
  setTimeout(() => URL.revokeObjectURL(url), 1000);
  button.textContent = '保存済み';
  button.classList.add('is-copied');
  restoreButtonText(button, originalText);
}

function outputHasStory(outputEl) {
  if (!outputEl || outputEl.classList.contains('empty')) return false;
  return charLength(stripStoryMakerFooter(outputEl.innerText || outputEl.textContent || '')) >= 40;
}

function isStoryGenerationActive() {
  const settingsEl = document.getElementById('settings');
  const generateButton = document.getElementById('btn-generate');
  return Boolean(settingsEl?.classList.contains('generating') || generateButton?.disabled);
}

export function installAlphapolisAssist() {
  const outputEl = document.getElementById('output');
  const rootEl = document.getElementById('alphapolis-assist');
  const checkbox = document.getElementById('alphapolis-assist-enable');
  const bodyEl = document.getElementById('alphapolis-assist-body');
  const previewEl = document.getElementById('alphapolis-form-preview');
  const statusEl = document.getElementById('alphapolis-assist-status');
  if (!outputEl || !rootEl || !checkbox || !bodyEl || !previewEl || !statusEl) return;

  let lastPreview = null;
  let queued = false;
  let busy = false;

  const setCopyControlsDisabled = disabled => {
    bodyEl.querySelectorAll('.alphapolis-copy-btn, .alphapolis-save-btn').forEach(button => {
      button.disabled = Boolean(disabled);
    });
  };

  const applyLockedUi = (value, message = '処理完了後に最新内容へ更新') => {
    const locked = Boolean(value);
    rootEl.classList.toggle('is-busy', locked);
    rootEl.setAttribute('aria-busy', locked ? 'true' : 'false');
    checkbox.disabled = locked || !outputHasStory(outputEl);
    setCopyControlsDisabled(locked);
    if (locked) statusEl.textContent = message;
  };

  const setBusy = value => {
    busy = Boolean(value);
    applyLockedUi(busy);
  };

  const refresh = () => {
    queued = false;
    const generationActive = isStoryGenerationActive();
    if (busy || generationActive) {
      applyLockedUi(true, generationActive ? '生成完了後に最新内容へ更新' : '処理完了後に最新内容へ更新');
      return;
    }
    applyLockedUi(false);
    const enabled = checkbox.checked;
    const canPreview = outputHasStory(outputEl);
    checkbox.disabled = !canPreview;
    bodyEl.classList.toggle('hidden', !enabled || !canPreview);
    if (!canPreview) {
      lastPreview = null;
      statusEl.textContent = '出力後に表示';
      previewEl.innerHTML = '';
      setCopyControlsDisabled(true);
      return;
    }
    const storyText = outputEl.innerText || outputEl.textContent || '';
    lastPreview = buildAlphapolisPreview({
      storyText,
      settings: readSettingsFromDom(),
    });
    statusEl.textContent = enabled
      ? `表示中: ${lastPreview.episodes.length}話 / ${lastPreview.tags.length}タグ候補`
      : 'チェックで表示';
    if (enabled) previewEl.innerHTML = renderAlphapolisPreview(lastPreview);
    setCopyControlsDisabled(!enabled);
  };

  const scheduleRefresh = () => {
    if (queued) return;
    queued = true;
    window.requestAnimationFrame(refresh);
  };

  checkbox.checked = false;
  checkbox.addEventListener('change', refresh);
  window.addEventListener('story-maker:alphapolis-busy', event => {
    setBusy(event.detail?.busy);
    if (!busy) scheduleRefresh();
  });
  window.addEventListener('story-maker:alphapolis-refresh', scheduleRefresh);

  bodyEl.addEventListener('click', event => {
    const saveButton = event.target?.closest?.('.alphapolis-save-btn');
    if (saveButton && !saveButton.disabled && !busy && lastPreview) {
      saveTextFile(lastPreview.copyAll, saveButton);
      return;
    }
    const button = event.target?.closest?.('.alphapolis-copy-btn');
    if (!button || button.disabled || busy || !lastPreview) return;
    copyText(getAlphapolisCopyValue(lastPreview, button.dataset.copyKind, {
      episodeIndex: button.dataset.copyIndex,
      tagIndex: button.dataset.copyIndex,
    }), button);
  });

  ['mode', 'theme', 'genre', 'worldview', 'target', 'era', 'ending', 'narr'].forEach(axis => {
    document.getElementById(`${axis}-custom`)?.addEventListener('input', scheduleRefresh);
    document.getElementById(`${axis}-custom`)?.addEventListener('change', scheduleRefresh);
  });
  document.addEventListener('click', event => {
    if (event.target?.closest?.('.chip, .btn-all-random, #btn-rand-mode')) {
      setTimeout(scheduleRefresh, 0);
    }
  });

  const observer = new MutationObserver(scheduleRefresh);
  observer.observe(outputEl, {
    childList: true,
    characterData: true,
    subtree: true,
    attributes: true,
    attributeFilter: ['class'],
  });
  const settingsEl = document.getElementById('settings');
  const generateButton = document.getElementById('btn-generate');
  if (settingsEl) {
    observer.observe(settingsEl, {
      attributes: true,
      attributeFilter: ['class'],
    });
  }
  if (generateButton) {
    observer.observe(generateButton, {
      childList: true,
      characterData: true,
      subtree: true,
      attributes: true,
      attributeFilter: ['disabled', 'class'],
    });
  }
  refresh();
}
