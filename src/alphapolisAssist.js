const MAX_TITLE_CHARS = 70;
const MAX_INTRODUCTION_CHARS = 1200;
const MAX_TAGS = 10;
const MAX_TAG_CHARS = 20;
const AI_GENERATED_TAG = 'AI生成作品';
const STORY_FOOTER_PATTERN = /\n?\s*(?:Created By AI Story Maker V[\d.]+|Generated By AI Story Maker V[\d.]+|Generated by Super FURU AI Story v[\d.]+)\s*$/i;
const TITLE_LABEL_PATTERN = /(?:^|\n)\s*(?:小説タイトル|タイトル|題名|作品名)\s*[:：]\s*([^\n]{1,100})/u;
const TITLE_LABEL_LINE_PATTERN = /^\s*(?:小説タイトル|タイトル|題名|作品名)\s*[:：]\s*([^\n]{1,100})\s*$/u;
const CHAPTER_HEADING_PATTERN = /^[\t \u3000]*(?:#{1,6}[\t \u3000]*)?(?:【[\t \u3000]*)?(?:(?:第[0-9０-９一二三四五六七八九十百千]+[章話節](?:[\t \u3000:：\-ー―・]+[^\n【】]{0,60})?)|(?:プロローグ|エピローグ|序章|終章)(?:[\t \u3000:：\-ー―・]+[^\n【】]{0,60})?)(?:[\t \u3000]*】)?[\t \u3000]*$/u;
const CHAPTER_HEADING_PREFIX_PATTERN = /^[\t \u3000]*(?:#{1,6}[\t \u3000]*)?(?:【[\t \u3000]*)?(?:(?:第[0-9０-９一二三四五六七八九十百千]+[章話節](?:[\t \u3000:：\-ー―・]+[^\n【】\s\u3000]{1,32})?)|(?:プロローグ|エピローグ|序章|終章)(?:[\t \u3000:：\-ー―・]+[^\n【】\s\u3000]{1,32})?)(?:[\t \u3000]*】)?[\t \u3000]+/u;
const STANDALONE_FINISH_PATTERN = /^[\t \u3000]*(?:【\s*)?完(?:\s*】)?[\t \u3000]*$/u;

