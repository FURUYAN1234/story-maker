export function getOutputModeLabel(mode) {
  return OUTPUT_MODE_LABELS[mode] || mode || '標準物語';
}

export function buildOutputModeStrictContract({ mode, modeLabel, axisText = '' } = {}) {
  if (mode === 'long' || /\blong\b|long[-\s_]*novel|長編/i.test(String(axisText || ''))) {
    return '';
  }

  const label = modeLabel || getOutputModeLabel(mode);
  const requirement = STRICT_MODE_REQUIREMENTS[mode] || STRICT_MODE_REQUIREMENTS.novel;
  return [
    '',
    '【v4.9.5 出力モード厳守 / この見出しは本文に出力しない】',
    `今回の出力モードは「${label}」。`,
    '最終出力は必ずこのモードの形式だけで書く。本文の途中や最後で別モードへ切り替えない。',
    '小説本文、メモ、解説、自己採点、プロンプト説明、英語の書式説明を混ぜない。',
    requirement,
    'この出力モード厳守文は本文に出力しない。',
  ].join('\n');
}

export function prependOutputModeStrictContract(text, contract) {
  const body = String(text || '');
  if (!contract || body.includes('【v4.9.5 出力モード厳守')) {
    return body;
  }
  return contract + body;
}

export function buildFinalOutputFormatCheck({ mode, modeLabel } = {}) {
  if (mode === 'long') {
    return '';
  }

  const label = modeLabel || getOutputModeLabel(mode);
  return [
    '',
    '【最終出力形式チェック】',
    `最後に必ず確認: 今回の出力モードは「${label}」。`,
    FINAL_FORMAT_CHECKS[mode] || FINAL_FORMAT_CHECKS.novel,
    'この最終形式チェック文は本文に出力しない。',
  ].join('\n');
}

