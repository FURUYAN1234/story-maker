// Validate the emitted schema, never infer speech from quotes in visual prose.
// Geometric/acting semantics remain subject to Nano's own STEP3 checks and
// generated-artwork review; this gate cannot prove the final drawing.
export function getNanoScenarioIssue(text = '') {
  const source = String(text).replace(/<thought>[\s\S]*?<\/thought>/gi, '').replace(/\r\n/g, '\n');
  const headers = [...source.matchAll(/^\[([1-4])コマ目(?:\s*[:：]\s*[起承転結])?\]\s*$/gm)];
  if (headers.map(h => h[1]).join(',') !== '1,2,3,4') return '4コマ見出しは1〜4の順に各1回必要です';
  const preface = source.slice(0, headers[0].index);
  for (const label of ['Topic', 'Logline', 'Location', 'VisualEvidence', 'Outfit', 'Punchline']) {
    if (!new RegExp('^'+label+':[^\\S\\n]*\\S[^\\n]*$', 'm').test(preface)) return `${label}が未記入です`;
  }
  if (!/^Scenario:\s*$/m.test(preface)) return 'Scenario:が必要です';
  for (let i = 0; i < headers.length; i++) {
    const panel = source.slice(headers[i].index, headers[i+1]?.index ?? source.length);
    const fail = message => `${i+1}コマ目: ${message}`;
    for (const label of ['EMOTION', 'Camera']) {
      if ([...panel.matchAll(new RegExp('^\\['+label+':[^\\S\\n]*[^\\]\\n]+\\]\\s*$', 'gm'))].length !== 1) return fail(`${label}タグは1つ必要です`);
    }
    const layoutLines = [...panel.matchAll(/^BalloonLayout\s*[:：]([^\n]*)$/gm)];
    const situations = [...panel.matchAll(/^状況\s*[:：]([^\n]*)$/gm)];
    if (layoutLines.length !== 1 || situations.length !== 1 || !situations[0][1].trim()) return fail('BalloonLayoutと状況は各1つ必要です');
    let layout;
    try { layout = JSON.parse(layoutLines[0][1]); } catch { return fail('BalloonLayoutのJSONを読み取れません'); }
    if (!Array.isArray(layout)) return fail('BalloonLayoutはJSON配列にしてください');
    const lines = panel.split('\n').map(line => line.trim()).filter(line => line && !/^(?:\[|BalloonLayout\s*[:：]|状況\s*[:：]|(?:表情|身体|演出|背景|リアクション)\s*[:：]|(?:Created|Generated) By AI Story Maker|【完】)/.test(line));
    const silent = lines.length === 1 && /^(?:無言|セリフなし|台詞なし)[。.!]?$/.test(lines[0]);
    if (!lines.length) return fail('無言コマにはセリフなしを明記してください');
    const speakers = [];
    if (!silent) for (const line of lines) {
      const quote = line.indexOf('「');
      if (quote <= 0 || !line.endsWith('」')) return fail('発話は独立したキャラ名「セリフ。」の行にしてください');
      let depth = 0;
      for (const [j, char] of [...line.slice(quote)].entries()) {
        if (char === '「') depth++;
        if (char === '」') depth--;
        if (depth < 0 || (depth === 0 && j < [...line.slice(quote)].length-1)) return fail('台詞の引用括弧が不整合です');
      }
      if (depth !== 0) return fail('台詞の引用括弧が閉じていません');
      if (!/[。！？!?]」$/.test(line)) return fail('台詞の終止記号が必要です');
      speakers.push(line.slice(0, quote).trim());
    }
    if (layout.length !== speakers.length) return fail('BalloonLayoutと台詞数が一致しません');
    for (let j = 0; j < layout.length; j++) {
      const item = layout[j];
      if (!item || item.speaker !== speakers[j]) return fail('BalloonLayoutの話者または台詞順が一致しません');
      if (!Number.isFinite(item.x) || item.x <= 0 || item.x >= 1 || (j > 0 && layout[j-1].x <= item.x)) return fail('BalloonLayoutのxは0〜1の範囲内で右→左へ厳密に減少させてください');
      if (!['anchor', 'route'].every(key => typeof item[key] === 'string' && item[key].trim())) return fail('BalloonLayoutのanchorとrouteが必要です');
    }
  }
  return '';
}

export function assertNanoScenarioOutput(text) {
  const issue = getNanoScenarioIssue(text);
  if (issue) throw Object.assign(new Error(`STEP2シナリオ形式エラー: ${issue}`), { code: 'NANO_SCENARIO_INVALID', draft: text });
  return text;
}

export function isNanoScenarioComplete(text) {
  return !getNanoScenarioIssue(text);
}

// The stable boundary is the assembled script, after all continuation chunks.
export function finalizeNanoScenarioOutput(mode, text) {
  return mode === '4koma_scenario' ? assertNanoScenarioOutput(text) : text;
}
