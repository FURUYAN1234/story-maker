export function buildRepairPrompt({ draft, issues, sceneContract }) {
  const issueText = (issues || [])
    .map(issue => `- ${issue.code}: ${issue.message}`)
    .join('\n');
  return [
    '次の小説本文を、本文だけの形でもう一度書き直してください。',
    '出力は修正版の本文だけ。説明、見出し、箇条書き、JSON、Markdownは禁止。',
    '漫画・脚本・メモ形式のラベルは禁止。「絵/状況:」「セリフ:」「1コマ目:」「ト書き:」「狙い:」などは通常の小説本文に変換してください。',
    'Story Bibleと場面契約を守り、足りない長さは自然な会話、行動、物の扱い、沈黙で補ってください。',
    '本文末に Created By などのフッターは書かないでください。',
    '',
    '修正理由',
    issueText || '- local validation failed',
    '',
    '終盤修復',
    '- 「心の奥」「少しだけ和らいだ」「気がした」「余韻」「静かに朝が始まった」などの感情総括で閉じず、最後は人物の選択、手の動き、物の配置変化で閉じる。',
    '- 「それは〜行為だった」「何を考えているのかは分からなかった。だが」「少なくとも、この瞬間は〜」「選択で終わった」「それが、自分にできること」「新しい始まり」の説明締めも削り、具体物と動作に置き換える。',
    '- 形式ラベルを削除しても情報は捨てない。状況は地の文へ、台詞は自然な会話へ移す。',
    '',
    '場面契約',
    sceneContract,
    '',
    '修正前本文',
    draft,
  ].join('\n');
}
